package com.phatvv9.wwarning.data.remote;

import android.util.Log;

import androidx.lifecycle.LiveData;
import androidx.lifecycle.MutableLiveData;

import com.google.firebase.Timestamp;
import com.google.firebase.auth.FirebaseAuth;
import com.google.firebase.firestore.DocumentReference;
import com.google.firebase.firestore.FirebaseFirestore;
import com.google.firebase.firestore.Query;
import com.google.firebase.firestore.QueryDocumentSnapshot;
import com.phatvv9.wwarning.model.Report;
import com.phatvv9.wwarning.util.GeoUtils;

import java.util.ArrayList;
import java.util.Date;
import java.util.List;

public class ReportRepository {
    private final FirebaseFirestore db;
    private final FirebaseAuth auth;
    private final MutableLiveData<List<Report>> reportsLiveData;
    private static final int EXPIRE_MINUTES = 60; // Default from app_settings

    public ReportRepository() {
        db = FirebaseFirestore.getInstance();
        auth = FirebaseAuth.getInstance();
        reportsLiveData = new MutableLiveData<>();
        listenToReports();
    }

    public LiveData<List<Report>> getReports() {
        return reportsLiveData;
    }

    private void listenToReports() {
        // Tuần 2: Snapshot listener trả LiveData<List<Report>>
        db.collection("reports")
                .whereEqualTo("status", "active")
                .addSnapshotListener((value, error) -> {
                    if (error != null) {
                        Log.e("ReportRepository", "Listen failed.", error);
                        return;
                    }

                    List<Report> reports = new ArrayList<>();
                    if (value != null) {
                        for (QueryDocumentSnapshot doc : value) {
                            Report report = doc.toObject(Report.class);
                            report.setId(doc.getId());
                            reports.add(report);
                        }
                    }
                    reportsLiveData.setValue(reports);
                });
    }

    public void createReport(String categoryId, double lat, double lng) {
        // Tuần 2: createReport(categoryId, lat, lng)
        String userId = auth.getCurrentUser() != null ? auth.getCurrentUser().getUid() : "anonymous";
        String geohash = GeoUtils.getGeoHash(lat, lng);
        
        Date now = new Date();
        Date expiresAtDate = new Date(now.getTime() + EXPIRE_MINUTES * 60000L);

        Report report = new Report(
                null, // id will be generated by Firestore
                userId,
                categoryId,
                "default", // severityId
                lat,
                lng,
                geohash,
                "", // description
                new Timestamp(now),
                new Timestamp(expiresAtDate)
        );

        db.collection("reports").add(report).addOnCompleteListener(task -> {
            if (task.isSuccessful()) {
                Log.d("ReportRepository", "Report added with ID: " + task.getResult().getId());
            } else {
                Log.e("ReportRepository", "Error adding report", task.getException());
            }
        });
    }
}
